def parse_ext_table():
    """Format metadata from js/formats.js (the app's single source of truth)."""
    src = open('js/formats.js').read()
    body = src[src.index('var EXT = {'):src.index('};', src.index('var EXT = {'))]
    out = {}
    for m in re.finditer(r"(\w+):\['(\w+)','((?:[^'\\]|\\.)*)','([^']*)'\]", body):
        out[m.group(1)] = [m.group(2), m.group(3).replace("\\'", "'"), m.group(4)]
    if len(out) < 60:
        sys.exit('could not parse the EXT table in js/formats.js')
    return out


