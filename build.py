def render_body(lines):
    out = []
    for line in lines:
        kind, text = line[:1], line[2:]
        if line.startswith('ul:'):
            out.append('<ul>' + ''.join('<li>%s</li>' % t for t in line[3:].split('|')) + '</ul>')
        elif kind == 'h':
            out.append('<h2>%s</h2>' % text)
        else:
            out.append('<p>%s</p>' % text)
    return '\n'.join(out)


