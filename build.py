# ------------------------------------------------------------- asset version
def asset_version():
    h = hashlib.sha1()
    for f in sorted(os.listdir('js')) + ['app.css', 'tools.css']:
        p = os.path.join('js', f) if f.endswith('.js') else os.path.join('css', f)
        h.update(open(p, 'rb').read())
    return h.hexdigest()[:8]


VER = asset_version()


